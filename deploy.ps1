$ErrorActionPreference = "Stop"

$Root = if ($PSScriptRoot) { $PSScriptRoot } else { (Get-Location).Path }
Set-Location -LiteralPath $Root

$Network = if ($env:NETWORK) { $env:NETWORK } else { "testnet" }
$Deployer = if ($env:DEPLOYER) { $env:DEPLOYER } else { "carebridge-deployer" }
$UsdcIssuer = if ($env:USDC_ISSUER) { $env:USDC_ISSUER } else { "GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5" }
$EnvFile = Join-Path $Root "app\.env.local"
$RpcUrl = if ($env:RPC_URL) { $env:RPC_URL } else { "https://soroban-testnet.stellar.org" }
$HorizonUrl = if ($env:HORIZON_URL) { $env:HORIZON_URL } else { "https://horizon-testnet.stellar.org" }

function Select-ContractId {
  param([string]$Text)
  $matches = [regex]::Matches($Text, "C[A-Z0-9]{55}")
  if ($matches.Count -eq 0) { return $null }
  return $matches[$matches.Count - 1].Value
}

if (-not (Get-Command stellar -ErrorAction SilentlyContinue)) {
  throw "Stellar CLI is required: https://developers.stellar.org/docs/tools/developer-tools/cli"
}

$deployerAddress = (& stellar keys address $Deployer 2>$null | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($deployerAddress)) {
  Write-Host "Generating deployer key '$Deployer'..."
  & stellar keys generate $Deployer --network $Network
  if ($LASTEXITCODE -ne 0) { throw "Failed to generate deployer key." }
  & stellar keys fund $Deployer --network $Network 2>$null
  $deployerAddress = (& stellar keys address $Deployer | Out-String).Trim()
  if ($LASTEXITCODE -ne 0) { throw "Failed to read deployer address." }
}

Write-Host "Deployer: $deployerAddress"

$contractId = $env:CONTRACT_ID
if ([string]::IsNullOrWhiteSpace($contractId)) {
  Write-Host "Building contract..."
  & stellar contract build
  if ($LASTEXITCODE -ne 0) { throw "Contract build failed." }

  $wasm = Join-Path $Root "target\wasm32v1-none\release\carebridge.wasm"
  if (-not (Test-Path -LiteralPath $wasm)) {
    $wasm = Join-Path $Root "target\wasm32-unknown-unknown\release\carebridge.wasm"
  }
  if (-not (Test-Path -LiteralPath $wasm)) {
    throw "Could not find the compiled carebridge.wasm"
  }

  Write-Host "Deploying $wasm to $Network..."
  $deployOutput = (& stellar contract deploy --wasm $wasm --source $Deployer --network $Network 2>&1 | Out-String)
  if ($LASTEXITCODE -ne 0) {
    throw "Deployment failed:`n$deployOutput"
  }
  $contractId = Select-ContractId $deployOutput
  if ([string]::IsNullOrWhiteSpace($contractId)) {
    throw "Deployment did not return a contract id:`n$deployOutput"
  }
  Write-Host "Contract: $contractId"
} else {
  Write-Host "Using existing contract: $contractId"
}

Write-Host "Resolving Stellar Asset Contract addresses..."
$xlmSac = Select-ContractId (& stellar contract id asset --asset native --network $Network 2>&1 | Out-String)
if ([string]::IsNullOrWhiteSpace($xlmSac)) {
  throw "Could not resolve the XLM SAC address."
}
$usdcSac = Select-ContractId (& stellar contract id asset --asset "USDC:$UsdcIssuer" --network $Network 2>&1 | Out-String)

$envDirectory = Split-Path -Parent $EnvFile
if (-not (Test-Path -LiteralPath $envDirectory)) {
  New-Item -ItemType Directory -Path $envDirectory | Out-Null
}

$stamp = [DateTime]::UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ")
$envContent = @"
# Generated by deploy.ps1 on $stamp
NEXT_PUBLIC_STELLAR_NETWORK=$Network
NEXT_PUBLIC_STELLAR_RPC_URL=$RpcUrl
NEXT_PUBLIC_STELLAR_HORIZON_URL=$HorizonUrl
NEXT_PUBLIC_CONTRACT_ID=$contractId
NEXT_PUBLIC_READ_ACCOUNT=$deployerAddress
NEXT_PUBLIC_XLM_SAC=$xlmSac
NEXT_PUBLIC_USDC_SAC=$usdcSac
NEXT_PUBLIC_DEFAULT_TOKEN=$xlmSac
"@

Set-Content -LiteralPath $EnvFile -Value $envContent -Encoding ASCII

Write-Host ""
Write-Host "Wrote $EnvFile"
Write-Host "  NEXT_PUBLIC_CONTRACT_ID=$contractId"
Write-Host "  NEXT_PUBLIC_XLM_SAC=$xlmSac"
Write-Host "  NEXT_PUBLIC_USDC_SAC=$(if ($usdcSac) { $usdcSac } else { '<unavailable>' })"
Write-Host ""
Write-Host "Next: cd app; npm install; npm run dev"
