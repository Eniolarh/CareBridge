#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

NETWORK="${NETWORK:-testnet}"
DEPLOYER="${DEPLOYER:-carebridge-deployer}"
USDC_ISSUER="${USDC_ISSUER:-GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5}"
ENV_FILE="app/.env.local"
RPC_URL="${RPC_URL:-https://soroban-testnet.stellar.org}"
HORIZON_URL="${HORIZON_URL:-https://horizon-testnet.stellar.org}"

if ! command -v stellar >/dev/null 2>&1; then
  echo "Stellar CLI is required: https://developers.stellar.org/docs/tools/developer-tools/cli" >&2
  exit 1
fi

if ! stellar keys address "$DEPLOYER" >/dev/null 2>&1; then
  echo "Generating deployer key '$DEPLOYER'..."
  stellar keys generate "$DEPLOYER" --network "$NETWORK"
  stellar keys fund "$DEPLOYER" --network "$NETWORK" || true
fi

DEPLOYER_ADDRESS="$(stellar keys address "$DEPLOYER" | tr -d '\r')"
echo "Deployer: $DEPLOYER_ADDRESS"

if [[ -n "${CONTRACT_ID:-}" ]]; then
  echo "Using existing contract: $CONTRACT_ID"
else
  echo "Building contract..."
  stellar contract build

  WASM="target/wasm32v1-none/release/carebridge.wasm"
  if [[ ! -f "$WASM" ]]; then
    WASM="target/wasm32-unknown-unknown/release/carebridge.wasm"
  fi
  if [[ ! -f "$WASM" ]]; then
    echo "Could not find the compiled carebridge.wasm" >&2
    exit 1
  fi

  echo "Deploying $WASM to $NETWORK..."
  DEPLOY_OUTPUT="$(stellar contract deploy --wasm "$WASM" --source "$DEPLOYER" --network "$NETWORK")"
  CONTRACT_ID="$(printf '%s\n' "$DEPLOY_OUTPUT" | grep -Eo 'C[A-Z0-9]{55}' | tail -n1 || true)"
  if [[ -z "$CONTRACT_ID" ]]; then
    echo "Deployment did not return a contract id:" >&2
    printf '%s\n' "$DEPLOY_OUTPUT" >&2
    exit 1
  fi
  echo "Contract: $CONTRACT_ID"
fi

echo "Resolving Stellar Asset Contract addresses..."
XLM_SAC="$(stellar contract id asset --asset native --network "$NETWORK" | grep -Eo 'C[A-Z0-9]{55}' | tail -n1 || true)"
USDC_SAC="$(stellar contract id asset --asset "USDC:$USDC_ISSUER" --network "$NETWORK" | grep -Eo 'C[A-Z0-9]{55}' | tail -n1 || true)"

if [[ -z "$XLM_SAC" ]]; then
  echo "Could not resolve the XLM SAC address." >&2
  exit 1
fi

mkdir -p "$(dirname "$ENV_FILE")"
cat > "$ENV_FILE" <<EOF
# Generated by deploy.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
NEXT_PUBLIC_STELLAR_NETWORK=$NETWORK
NEXT_PUBLIC_STELLAR_RPC_URL=$RPC_URL
NEXT_PUBLIC_STELLAR_HORIZON_URL=$HORIZON_URL
NEXT_PUBLIC_CONTRACT_ID=$CONTRACT_ID
NEXT_PUBLIC_READ_ACCOUNT=$DEPLOYER_ADDRESS
NEXT_PUBLIC_XLM_SAC=$XLM_SAC
NEXT_PUBLIC_USDC_SAC=$USDC_SAC
NEXT_PUBLIC_DEFAULT_TOKEN=$XLM_SAC
EOF

echo
echo "Wrote $ENV_FILE"
echo "  NEXT_PUBLIC_CONTRACT_ID=$CONTRACT_ID"
echo "  NEXT_PUBLIC_XLM_SAC=$XLM_SAC"
echo "  NEXT_PUBLIC_USDC_SAC=${USDC_SAC:-<unavailable>}"
echo
echo "Next: cd app && npm install && npm run dev"
